import { CONFIG } from '@/lib/config';

export type Classification = 'weak' | 'medium' | 'strong' | 'insufficient_data';

export interface TopicAttemptStats {
  topicId: string;
  topicName: string;
  parentId?: string | null;
  attempted: number;
  correct: number;
  incorrect: number;
  accuracy: number;
  classification: Classification;
  reason: string;
  isLowConfidence: boolean;
}

export interface AttemptResponseItem {
  topicId: string;
  subtopicId?: string | null;
  isCorrect: boolean;
  attemptId: string;
  attemptIndex?: number; // 0 is oldest, higher is more recent
}

/**
 * Deterministic Gap Classifier.
 * Rules:
 * - Minimum attempts threshold: below MIN_ATTEMPTS_FOR_CLASSIFICATION -> 'insufficient_data'
 * - Between MIN_ATTEMPTS and LOW_CONFIDENCE_MAX_ATTEMPTS -> add "Low confidence" warning
 * - Accuracy thresholds:
 *     >= STRONG_THRESHOLD (default 0.75) -> 'strong'
 *     >= MEDIUM_THRESHOLD (default 0.50) -> 'medium'
 *     < MEDIUM_THRESHOLD -> 'weak'
 * - Human-readable reason generated by code.
 */
export function classifyTopicStats(
  topicId: string,
  topicName: string,
  attempted: number,
  correct: number,
  parentId?: string | null
): TopicAttemptStats {
  const {
    STRONG_THRESHOLD,
    MEDIUM_THRESHOLD,
    MIN_ATTEMPTS_FOR_CLASSIFICATION,
    LOW_CONFIDENCE_MAX_ATTEMPTS,
  } = CONFIG;

  const incorrect = attempted - correct;
  const accuracy = attempted > 0 ? correct / attempted : 0;
  const pct = Math.round(accuracy * 100);

  if (attempted < MIN_ATTEMPTS_FOR_CLASSIFICATION) {
    return {
      topicId,
      topicName,
      parentId,
      attempted,
      correct,
      incorrect,
      accuracy,
      classification: 'insufficient_data',
      reason: `Only ${attempted} question${attempted === 1 ? '' : 's'} attempted; need at least ${MIN_ATTEMPTS_FOR_CLASSIFICATION} for a reliable classification.`,
      isLowConfidence: true,
    };
  }

  const isLowConfidence = attempted <= LOW_CONFIDENCE_MAX_ATTEMPTS;
  const confidenceNote = isLowConfidence
    ? ` (Low confidence: based on only ${attempted} attempts)`
    : '';

  let classification: Classification;
  let reason: string;

  if (accuracy >= STRONG_THRESHOLD) {
    classification = 'strong';
    reason = `${correct} of ${attempted} correct (${pct}%) meets strong threshold (${Math.round(
      STRONG_THRESHOLD * 100
    )}%)${confidenceNote}.`;
  } else if (accuracy >= MEDIUM_THRESHOLD) {
    classification = 'medium';
    reason = `${correct} of ${attempted} correct (${pct}%) meets medium threshold (${Math.round(
      MEDIUM_THRESHOLD * 100
    )}%-${Math.round(STRONG_THRESHOLD * 100 - 1)}%)${confidenceNote}.`;
  } else {
    classification = 'weak';
    reason = `${correct} of ${attempted} correct (${pct}%) is below medium threshold (${Math.round(
      MEDIUM_THRESHOLD * 100
    )}%)${confidenceNote}.`;
  }

  return {
    topicId,
    topicName,
    parentId,
    attempted,
    correct,
    incorrect,
    accuracy,
    classification,
    reason,
    isLowConfidence,
  };
}

/**
 * Computes cumulative stats across multiple attempts with recency weighting.
 * Latest attempt counts for RECENCY_WEIGHT (e.g. 0.6), earlier attempts for 1 - RECENCY_WEIGHT.
 */
export function computeCumulativeClassification(
  topicId: string,
  topicName: string,
  historicalAttempts: { attempted: number; correct: number }[]
): TopicAttemptStats {
  const { RECENCY_WEIGHT } = CONFIG;

  const totalAttempted = historicalAttempts.reduce((acc, a) => acc + a.attempted, 0);
  const totalCorrect = historicalAttempts.reduce((acc, a) => acc + a.correct, 0);

  if (totalAttempted < CONFIG.MIN_ATTEMPTS_FOR_CLASSIFICATION) {
    return classifyTopicStats(topicId, topicName, totalAttempted, totalCorrect);
  }

  if (historicalAttempts.length <= 1) {
    return classifyTopicStats(topicId, topicName, totalAttempted, totalCorrect);
  }

  // Multi-attempt recency weighted accuracy
  const latest = historicalAttempts[historicalAttempts.length - 1];
  const latestAcc = latest.attempted > 0 ? latest.correct / latest.attempted : 0;

  const olderAttempts = historicalAttempts.slice(0, -1);
  const olderAttempted = olderAttempts.reduce((acc, a) => acc + a.attempted, 0);
  const olderCorrect = olderAttempts.reduce((acc, a) => acc + a.correct, 0);
  const olderAcc = olderAttempted > 0 ? olderCorrect / olderAttempted : latestAcc;

  const weightedAccuracy = latestAcc * RECENCY_WEIGHT + olderAcc * (1 - RECENCY_WEIGHT);

  // Generate classification from weighted accuracy
  const isLowConfidence = totalAttempted <= CONFIG.LOW_CONFIDENCE_MAX_ATTEMPTS;
  const confidenceNote = isLowConfidence
    ? ` (Low confidence: ${totalAttempted} attempts)`
    : '';

  let classification: Classification;
  let reason: string;
  const pct = Math.round(weightedAccuracy * 100);

  if (weightedAccuracy >= CONFIG.STRONG_THRESHOLD) {
    classification = 'strong';
    reason = `Recency-weighted accuracy ${pct}% (${totalCorrect}/${totalAttempted} total) meets strong threshold${confidenceNote}.`;
  } else if (weightedAccuracy >= CONFIG.MEDIUM_THRESHOLD) {
    classification = 'medium';
    reason = `Recency-weighted accuracy ${pct}% (${totalCorrect}/${totalAttempted} total) meets medium threshold${confidenceNote}.`;
  } else {
    classification = 'weak';
    reason = `Recency-weighted accuracy ${pct}% (${totalCorrect}/${totalAttempted} total) is below threshold${confidenceNote}.`;
  }

  return {
    topicId,
    topicName,
    attempted: totalAttempted,
    correct: totalCorrect,
    incorrect: totalAttempted - totalCorrect,
    accuracy: weightedAccuracy,
    classification,
    reason,
    isLowConfidence,
  };
}
